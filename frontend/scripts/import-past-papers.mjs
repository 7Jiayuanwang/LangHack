import fs from 'node:fs/promises'
import path from 'node:path'
import { parsePaperJson, parsePaperMarkdown } from '../src/utils/pastPaperImporter.js'

const args = process.argv.slice(2)
const optionValue = (name, fallback = '') => {
  const index = args.indexOf(name)
  return index >= 0 ? args[index + 1] : fallback
}

const inputPath = optionValue('--input') || (args[0]?.startsWith('--') ? '' : args[0])
const forcedCategory = optionValue('--category')
const outputPath = path.resolve(optionValue('--output', 'src/data/importedPastPapers.js'))
const serverUrl = optionValue('--server').replace(/\/$/, '')
const token = optionValue('--token') || process.env.LANGHACK_ADMIN_TOKEN || ''

if (!inputPath || args.includes('--help')) {
  console.log(`Usage:
  npm run import:papers -- <file-or-directory> [options]

Options:
  --category cet4|cet6|postgraduate   Force one category for every file
  --output <file>                     Output module (default: src/data/importedPastPapers.js)
  --server <url>                      Upload to a running LangHack server
  --token <jwt>                       Admin access token (or LANGHACK_ADMIN_TOKEN)

Category is inferred from file names containing 四级/cet4, 六级/cet6, or 考研/postgraduate.`)
  process.exit(inputPath ? 0 : 1)
}

function inferCategory(fileName) {
  if (forcedCategory) return forcedCategory
  const name = fileName.toLowerCase()
  if (name.includes('四级') || name.includes('cet4')) return 'cet4'
  if (name.includes('六级') || name.includes('cet6')) return 'cet6'
  if (name.includes('考研') || name.includes('postgraduate')) return 'postgraduate'
  throw new Error('无法从文件名识别分类，请使用 --category')
}

async function collectFiles(target) {
  const absolute = path.resolve(target)
  const stat = await fs.stat(absolute)
  if (stat.isFile()) return [absolute]

  const files = []
  for (const entry of await fs.readdir(absolute, { withFileTypes: true })) {
    const child = path.join(absolute, entry.name)
    if (entry.isDirectory()) files.push(...await collectFiles(child))
    else if (/\.(md|json)$/i.test(entry.name)) files.push(child)
  }
  return files.sort((a, b) => a.localeCompare(b, 'zh-CN'))
}

async function parseFile(filePath) {
  const text = await fs.readFile(filePath, 'utf8')
  const fallback = {
    category: inferCategory(path.basename(filePath)),
    title: path.basename(filePath, path.extname(filePath)),
    duration: 30
  }
  return filePath.toLowerCase().endsWith('.json')
    ? parsePaperJson(text, fallback)
    : parsePaperMarkdown(text, fallback)
}

const files = await collectFiles(inputPath)
if (files.length === 0) throw new Error('目录中没有 .md 或 .json 文件')

const papers = []
const failures = []
for (const file of files) {
  try {
    const paper = await parseFile(file)
    papers.push(paper)
    console.log(`[OK] ${path.basename(file)} -> ${paper.title} (${paper.questions.length} questions)`)
  } catch (error) {
    failures.push({ file, message: error.message })
    console.error(`[FAIL] ${file}\n       ${error.message}`)
  }
}

if (failures.length) {
  console.error(`\nImport stopped: ${failures.length}/${files.length} files failed validation. Output was not changed.`)
  process.exit(1)
}

const ids = new Set()
for (const paper of papers) {
  const stableId = `${paper.category}-${paper.title}`
    .toLowerCase()
    .replace(/[^a-z0-9\u4e00-\u9fff]+/g, '-')
    .replace(/^-|-$/g, '')
  paper.id = `batch-${stableId}`
  if (ids.has(paper.id)) throw new Error(`试卷名称重复：${paper.title}`)
  ids.add(paper.id)
  paper.custom = false
  paper.source = 'batch-import'
  paper.questions = paper.questions.map((question, index) => ({ ...question, id: `${paper.id}-q-${index + 1}` }))
}

if (serverUrl) {
  if (!token) throw new Error('服务端上传需要 --token 或 LANGHACK_ADMIN_TOKEN')
  for (const paper of papers) {
    const response = await fetch(`${serverUrl}/api/past-papers`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` },
      body: JSON.stringify(paper)
    })
    const result = await response.json().catch(() => ({}))
    if (!response.ok || result.code !== 200) {
      throw new Error(`服务端导入失败：${paper.title} - ${result.message || `HTTP ${response.status}`}`)
    }
    console.log(`[UPLOADED] ${paper.title}`)
  }
  console.log(`\nUploaded ${papers.length} papers. They are now available to all students.`)
  process.exit(0)
}

const moduleText = `// Generated by scripts/import-past-papers.mjs. Do not edit manually.\n\nexport const importedPastPapers = ${JSON.stringify(papers, null, 2)}\n`
await fs.mkdir(path.dirname(outputPath), { recursive: true })
await fs.writeFile(outputPath, moduleText, 'utf8')
console.log(`\nGenerated ${outputPath}: ${papers.length} papers, ${papers.reduce((sum, paper) => sum + paper.questions.length, 0)} questions`)
